#!/usr/bin/env node
import { readdir, readFile, writeFile, mkdir } from 'node:fs/promises'
import path from 'node:path'
import sharp from 'sharp'

const eventsPath = path.resolve('src/data/events.json')
const events = JSON.parse(await readFile(eventsPath, 'utf8'))
const eventIds = ['career-panel-granada', 'stem-into-the-night-2026']
const updates = []
const quote = (value) => "'" + value.replaceAll("'", "''") + "'"

for (const id of eventIds) {
  const event = events.find((item) => item.id === id)
  if (!event) throw new Error(`Missing event: ${id}`)
  const folder = path.resolve('public/images/events', id)
  const names = (await readdir(path.join(folder, 'photos')))
    .filter((name) => /\.(jpe?g|png|webp|avif)$/i.test(name))
    .sort((a, b) => a.localeCompare(b, 'en', { numeric: true }))
  if (!names.length) continue
  if (names.length > 40) throw new Error(`${id}: galleries support at most 40 photos`)
  await mkdir(path.join(folder, 'gallery'), { recursive: true })
  const gallery = []
  const seen = new Set()
  for (const name of names) {
    const output = `${path.parse(name).name}.webp`
    if (seen.has(output)) throw new Error(`Duplicate output filename: ${output}`)
    seen.add(output)
    await sharp(path.join(folder, 'photos', name)).rotate()
      .resize({ width: 1800, height: 1800, fit: 'inside', withoutEnlargement: true })
      .webp({ quality: 82 }).toFile(path.join(folder, 'gallery', output))
    gallery.push(`/images/events/${id}/gallery/${output}`)
  }
  const oldAlts = new Map((event.gallery ?? []).map((url, index) => [url, event.galleryAlts?.[index]]))
  event.gallery = gallery
  event.galleryAlts = gallery.map((url, index) => oldAlts.get(url) || `${event.title} event photo ${index + 1}`)
  const cover = gallery.includes(event.image) ? event.image : gallery[0]
  event.image = cover
  event.heroImage = cover
  event.imageAlt = event.galleryAlts[gallery.indexOf(cover)]
  event.heroImageAlt = event.imageAlt
  const media = Object.fromEntries(['image', 'heroImage', 'imageAlt', 'heroImageAlt', 'gallery', 'galleryAlts'].map((key) => [key, event[key]]))
  updates.push(`update public.events\nset media = coalesce(media, '{}'::jsonb) || ${quote(JSON.stringify(media))}::jsonb\nwhere id = ${quote(id)};`)
  console.log(`${event.title}: ${gallery.length} photos connected`)
}
await writeFile(eventsPath, JSON.stringify(events, null, 2) + '\n')
await writeFile('supabase/operator-updates/20261109_event_photos.sql',
  '-- Generated by npm run photos:sync. Apply through the existing operator release workflow.\n-- Updates only photo fields; preserves other media and event fields.\nbegin;\n\n' + updates.join('\n\n') + '\n\ncommit;\n')
